package ru.centraluniversity.workload;

/**
 * Нагрузка на сборщик мусора: одна итерация работы.
 * Бенчмарк многократно вызывает {@link #run()} и замеряет, сколько итераций
 * в секунду (или среднее время) выдерживает нагрузка под конкретным коллектором.
 */
public interface GcWorkload {

    /**
     * Имя нагрузки - попадает в названия бенчмарков и в отчёт.
     */
    String name();

    /**
     * Одна итерация: аллокации и полезная работа.
     */
    void run();
}
